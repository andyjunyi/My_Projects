# Remove duplicates (keep first occurrence)
seen = set()
VOCAB_DEDUP = []
for item in VOCAB:
    word = item[0]
    if word not in seen:
        seen.add(word)
        VOCAB_DEDUP.append(item)

# Build rows
rows = []
for word, kk, zh, counts in VOCAB_DEDUP:
    assert len(counts) == 13, f"Wrong count length for {word}: {len(counts)}"
    total = sum(counts)
    row = {
        'word': word,
        'kk_phonetics': kk,
        'chinese_meaning': zh,
        'total': total,
    }
    for y, c in zip(YEARS, counts):
        row[str(y)] = c
    rows.append(row)

# Sort by total desc, then word asc
rows.sort(key=lambda r: (-r['total'], r['word']))

# Write CSV with UTF-8-sig
FIELDS = ['word','kk_phonetics','chinese_meaning','total'] + [str(y) for y in YEARS]
out_path = r'E:\ClaudeCode Projects\cap-eng\vocab_by_year.csv'
with open(out_path, 'w', newline='', encoding='utf-8-sig') as f:
    writer = csv.DictWriter(f, fieldnames=FIELDS)
    writer.writeheader()
    writer.writerows(rows)

print(f"Written {len(rows)} words to {out_path}")
print("\nTop 20 words by frequency:")
for i, r in enumerate(rows[:20], 1):
    print(f"  {i:2d}. {r['word']:<20s} total={r['total']}")
